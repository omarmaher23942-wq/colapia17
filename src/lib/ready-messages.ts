// ready-messages.ts — رسائل قصيرة جاهزة للنسخ يرسلها التاجر لزبائنه (D12): تأكيد، شحن، تقييم، عودة للمخزون، تأخر.
// عامة بلا اسم عميل ولا رقم طلب (يكملها التاجر في واتساب)، بمخاطبة بالجمع تشمل الجميع. خالصة ومختبَرة.

export type ReadyMessage = { key: string; title: string; when: string; text: string };

/** يزيل الأسطر الفارغة المتكررة ويقصّ الأطراف. */
const tidy = (s: string) => s.replace(/\n{3,}/g, "\n\n").trim();

export function readyMessages(storeName: string, storeUrl?: string | null): ReadyMessage[] {
  const name = storeName.trim() || "متجرنا";
  const link = storeUrl ? `\n${storeUrl.replace(/^https?:\/\//, "")}` : "";
  return [
    {
      key: "confirm",
      title: "تأكيد الطلب",
      when: "فور وصول طلب جديد",
      text: tidy(`أهلاً بكم، شكراً لاختياركم ${name}.\nوصلنا طلبكم ونحتاج تأكيد العنوان ورقم الهاتف قبل التجهيز. هل البيانات صحيحة؟`),
    },
    {
      key: "shipped",
      title: "تم الشحن",
      when: "عند تسليم الطلب لشركة الشحن",
      text: tidy(`طلبكم من ${name} خرج للشحن الآن.\nسيتواصل معكم مندوب الشحن قبل التسليم، فيرجى إبقاء الهاتف متاحاً وتجهيز المبلغ المطلوب إن كان الدفع عند الاستلام.`),
    },
    {
      key: "review",
      title: "طلب تقييم",
      when: "بعد التسليم بيومين تقريباً",
      text: tidy(`نأمل أن طلبكم نال إعجابكم.\nرأيكم يهمنا ويساعد غيركم على الاختيار، وتقييمكم يستغرق دقيقة واحدة.${link}`),
    },
    {
      key: "stock",
      title: "عاد للمخزون",
      when: "لمن سأل عن منتج نافد",
      text: tidy(`المنتج الذي سألتم عنه عاد متاحاً في ${name}.\nالكمية محدودة، ويمكنكم الطلب مباشرة من الرابط.${link}`),
    },
    {
      key: "delay",
      title: "اعتذار عن تأخر",
      when: "عند تأخر التسليم عن الموعد",
      text: tidy(`نعتذر عن تأخر وصول طلبكم، ونتابعه مع شركة الشحن الآن.\nسنوافيكم بموعد التسليم المؤكد في أقرب وقت، وشكراً لصبركم.`),
    },
  ];
}
