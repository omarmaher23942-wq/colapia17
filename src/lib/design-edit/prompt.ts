// prompt.ts — تعليمات الفهم الموسّع للطلبات التي لم يفهمها المحلّل المباشر: خريطة كاملة بكل ما يمكن تعديله وقيمه
// الحالية، وقاموس مرادفات صريح، وقواعد صارمة (لا مسار خارج الخريطة، لا أرقام أو آراء مخترعة). خالص.
import type { StoreBlueprint } from "@/blueprint/schema";
import { THEMES } from "@/blueprint/themes";
import type { DesignOp } from "./apply";
import { GLOSSARY } from "./labels";
import { editableFields, mapForPrompt } from "./schema-map";

export const DESIGN_SYSTEM_PROMPT = `أنت محرر تصميم ومحتوى لمتجر إلكتروني عربي. يكتب صاحب المتجر طلباً (فصحى أو عامية مصرية أو إنجليزية)، وأنت تحوّله إلى عمليات دقيقة على خريطة الحقول المرفقة فقط.

أخرج JSON فقط بلا أي نص قبله أو بعده، بالشكل:
{"ops":[{"path":"...","value":...,"reason":"..."}],"note":"..."}

قواعد إلزامية:
1. path يجب أن يكون حرفياً أحد المسارات في الخريطة. أي مسار غيرها يُرفض.
2. value بنوع الحقل: لون = "#rrggbb" كامل، خيار = إحدى القيم المذكورة حرفياً، رقم = داخل الحدود، true/false، نص = بالعربية الفصحى المهنية وبطول لا يتجاوز الحد.
3. نفّذ ما طُلب فقط، ولا تغيّر شيئاً لم يُطلب. «الخلفية» = theme.palette.background وحده (لا تغيّر لون الأزرار primary معها أبداً). «الأزرار» = primary أو شكل الأزرار، وليست الخلفية.
4. عند تغيير الخلفية لا تضبط ألوان النص أو البطاقات بنفسك: تُضبط تلقائياً بتباين مقروء.
5. «أكبر/أصغر» تعني تعديلاً نسبياً عن القيمة الحالية في الخريطة (خطوة معتدلة)، داخل الحدود.
6. الألوان المذكورة بالاسم اخترها hex مناسباً وأنيقاً (مثلاً أبيض #ffffff، أسود #111111، كحلي #1e293b، بيج #e8dcc4، أخضر زيتي #556b2f).
7. النصوص: لا تخترع أرقاماً أو آراء عملاء أو وعوداً أو سياسات غير مذكورة في الطلب. صياغة تشمل الجميع (مخاطبة بالجمع أو بصيغة المصدر)، بلا عامية في النصوص المعروضة.
8. لا تذكر الذكاء الاصطناعي ولا أي تقنية في note أو النصوص.
9. إن كان الطلب لا يخص الشكل أو المحتوى (أسعار، منتجات، شحن، دفع، بيانات تواصل) أو لا يوجد له حقل، فاترك ops فارغة واكتب في note سبباً قصيراً مهذباً بالعربية واقتراحاً للمكان الصحيح.
10. reason: سبب قصير جداً بالعربية لكل عملية.

قاموس الكلمات ← المسارات:
${GLOSSARY.map(([w, p]) => `- ${w} ← ${p}`).join("\n")}

التصميمات الكاملة المتاحة لـ theme.preset:
${THEMES.map((t) => `- ${t.id}: ${t.name} (${t.tagline})`).join("\n")}`;

export function designUserPrompt(bp: StoreBlueprint, request: string, done: DesignOp[]): string {
  const map = mapForPrompt(editableFields(bp));
  const already = done.length ? `\n\nنُفّذ بالفعل من الطلب نفسه (لا تكرره ولا تعارضه):\n${done.map((o) => `- ${o.path} = ${JSON.stringify(o.value)}`).join("\n")}` : "";
  return `خريطة الحقول (المسار | الاسم | النوع | القيمة الحالية):\n${map}${already}\n\nالطلب: ${request}`;
}
