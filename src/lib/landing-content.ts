/** كل نص مرئي (بلا روابط) لاختبارات الصدق والعبارات الممنوعة. */
export function allCopy(): string[] {
  const out: string[] = [BRAND.tagline, DEFINITION, SITE_DESCRIPTION];
  for (const s of SERVICES) out.push(s.title, s.definition, s.example);
  for (const s of STEPS) out.push(s.title, s.text);
  out.push(...WORKING_PRINCIPLES);
  for (const w of WHY) out.push(w.title, w.text);
  for (const w of WORKS) out.push(w.name, w.kind, w.summary, ...w.details, w.cta, w.clientNote ?? "");
  for (const f of FAQ) out.push(f.q, f.a);
  out.push(ABOUT.lead, ...ABOUT.what);
  for (const v of ABOUT.values) out.push(v.title, v.text);
  return out.filter(Boolean);
}
